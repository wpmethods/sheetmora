<?php
/**
 * Generate the authenticated Google Apps Script receiver.
 *
 * @package SM
 */

namespace SM;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/** Generates a receiver for the selected schema. */
class SM_Script_Generator {
	/**
	 * Field definitions.
	 *
	 * @var array
	 */
	private $available_fields;

	/**
	 * Set the available schema.
	 *
	 * @param array $available_fields Field definitions.
	 */
	public function __construct( $available_fields ) {
		$this->available_fields = $available_fields;
	}

	/**
	 * Generate the script without evaluating any remote code in WordPress.
	 *
	 * @param array $selected_fields Validated field keys.
	 * @return string
	 */
	public function generate_script( $selected_fields ) {
		$fields = array();
		foreach ( $selected_fields as $key ) {
			if ( isset( $this->available_fields[ $key ] ) ) {
				$fields[ $key ] = $this->available_fields[ $key ]['label'];
			}
		}
		$config = array(
			'secret' => SM_To_Google_Sheets::get_secret(),
			'fields' => $fields,
		);
		/** Filter receiver configuration for installed extensions. */
		$config   = apply_filters( 'sm_script_config', $config );
		$resolver = "function getSheetNames(data) {\n  return ['WooCommerce Orders'];\n}\n";
		/** Filter the sheet resolver supplied by an installed extension. */
		$resolver = apply_filters( 'sm_script_sheet_resolver', $resolver );
		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Read a bundled local template, never a remote URL.
		$source = file_get_contents( SM_PATH . 'assets/js/sm-google-apps-script.js' );
		return '// Generated by SheetMora. Keep this script private.' . "\n"
			. 'const SM_CONFIG = ' . wp_json_encode( $config, JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT ) . ";\n"
			. $resolver . "\n" . $source;
	}
}
